export function absoluteUrl(route) {
  return route === "/" ? SITE.url : `${SITE.url}${route}`;
}

export function buildMetadata(route) {
  const page = PAGE_SEO[route];
  if (!page) throw new Error(`No PAGE_SEO entry for route "${route}"`);

  const url = absoluteUrl(route);
  const image = {
    url: `${SITE.url}${SITE.defaultOgImage}`,
    width: 1200,
    height: 630,
    alt: page.title,
  };

  return {
    title: { absolute: page.title },
    description: page.description,
    alternates: { canonical: url },
    openGraph: {
      type: "website",
      locale: SITE.locale,
      url,
      siteName: SITE.name,
      title: page.title,
      description: page.description,
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: page.title,
      description: page.description,
      images: [image.url],
    },
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        "max-image-preview": "large",
        "max-snippet": -1,
        "max-video-preview": -1,
      },
    },
  };
}
